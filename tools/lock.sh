#!/usr/bin/env bash
# Regenerate requirements.txt from pyproject.toml: every package pinned to one
# version with its SHA-256 hashes, for Linux x86_64, Linux aarch64 (DGX Spark)
# and Windows x86_64.
#
# Uses uv. In a BUILD office pod, uv comes from tool-bin's pinned-bin (exact
# bytes, SHA-256 checked); elsewhere, set UV to a uv binary you trust.
# After running: review the diff, run the tests and tools/smoke_random_weights.py.
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -z "${UV:-}" ]]; then
  if [[ -f /srv/tool-bin/pinned-bin/pinned_bin.py ]]; then
    UV="$(python3 /srv/tool-bin/pinned-bin/pinned_bin.py path uv | tail -n 1)"
  else
    UV="$(command -v uv)"
  fi
fi

"$UV" lock --upgrade
"$UV" export --format requirements-txt --no-emit-project --no-header --quiet \
  --output-file requirements.txt.tmp
{
  echo "# Generated by tools/lock.sh from pyproject.toml. Do not edit by hand."
  echo "# Install: pip install --require-hashes -r requirements.txt"
  cat requirements.txt.tmp
} > requirements.txt
rm -f requirements.txt.tmp uv.lock
echo "requirements.txt updated; review the diff."
